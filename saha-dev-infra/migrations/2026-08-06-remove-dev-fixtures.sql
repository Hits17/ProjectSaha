-- =============================================================================
-- Remove development fixture data from the production database — 2026-08-06
--
-- Companion to security/AUDIT.md SAHA-037. Two problems, one cause.
--
-- 1. Listing fb037599 "Nano-Coating Process v3" carries THREE executed deals,
--    all typed Exclusive for the same territory and 36-month term, two of them
--    completed and disbursed. Three exclusive licences for one territory are
--    logically contradictory — this is the double-sale condition the audit
--    describes, and it blocked the exclusivity index from being created.
--
-- 2. Two fixture listings are PUBLISHED, so test artefacts have been sitting in
--    the live public corpus alongside the demo seed.
--
-- Both trace to Sprint-era test fixtures left in the production database:
-- accounts named test_s3@, e2e_<epoch>@, seller_s6_<epoch>@, buyer_s6_<epoch>@,
-- comm_<hash>@. They were generated by automated test runs against this
-- database and never represented anything real.
--
-- WHY DELETE RATHER THAN CANCEL. Cancelling implies a deal that existed and was
-- called off. These did not exist in any meaningful sense. More importantly,
-- completed -> cancelled is not a legal transition in the application's own
-- state machine (see _VALID_TRANSITIONS), so forcing it would write a false
-- statement into the transaction record to make a constraint fit. That is a
-- softer version of exactly what the audit argues against. Removing fixture
-- rows is honest; rewriting financial outcomes is not.
--
-- The founder@saha.local admin account and the July demo seed
-- (demo01-10@saha.test, 100 listings) are NOT touched.
--
-- Every action here is recorded in audit_logs, which is append-only.
--
-- RUN AS: postgres.
--
-- Steps 1-2 are ordinary DML that `saha` can perform, but step 3 is CREATE INDEX,
-- which requires table ownership — and `transactions` is owned by postgres. Since
-- the whole thing is one transaction, a permission failure in step 3 rolls back
-- the deletes too. Running the lot as the owner keeps it atomic.
--
--   sudo -u postgres psql -d saha -f /tmp/saha-fixtures.sql
--
-- (postgres cannot read files under ~/Downloads — no directory traversal — so
--  stage a copy in /tmp or pipe it on stdin.)
-- =============================================================================

BEGIN;

-- ── 1. Drop the two superseded deals on listing fb037599 ────────────────────
-- Keeps 271dbd37 (the original $75,000 deal, which carries the two reviews).
-- Disbursements go first: there is no ON DELETE CASCADE at the database level.

DELETE FROM disbursements
 WHERE transaction_id IN (
   'd428e778-e61f-4304-9178-873f2bb8665c',   -- signed, $40,000, never funded
   '7c772c15-1933-4456-ba4c-ab1b34957e2b'    -- completed, $40,000, disbursed
 );

DELETE FROM transactions
 WHERE id IN (
   'd428e778-e61f-4304-9178-873f2bb8665c',
   '7c772c15-1933-4456-ba4c-ab1b34957e2b'
 );


-- ── 2. Archive published fixture listings ───────────────────────────────────
-- Removes them from the public corpus without destroying them. `archived` is a
-- real product status and this is reversible.

UPDATE ip_listings l
   SET status = 'archived', updated_at = NOW()
  FROM users u
 WHERE u.id = l.creator_id
   AND l.status = 'published'
   AND (u.email LIKE '%\_s6\_%@saha.local'
     OR u.email LIKE 'e2e\_%@saha.local'
     OR u.email LIKE 'test\_s3@saha.local'
     OR u.email LIKE 'comm\_%@saha.local');


-- ── 3. Create the exclusivity index now the conflict is gone ────────────────
-- Same conditional form as the hardening migration: create it when the data
-- permits, report precisely what blocks it when it does not.

DO $$
DECLARE conflicts TEXT; n INT;
BEGIN
    SELECT count(*), string_agg(listing_id::text || ' (' || cnt || ')', ', ')
      INTO n, conflicts
      FROM (
        SELECT listing_id, count(*) AS cnt FROM transactions
         WHERE status IN ('signed','escrow_pending','escrow_funded',
                          'disbursement_pending','completed')
         GROUP BY listing_id HAVING count(*) > 1
      ) d;

    IF n = 0 THEN
        CREATE UNIQUE INDEX IF NOT EXISTS uq_listing_single_executed_deal
            ON transactions (listing_id)
            WHERE status IN ('signed','escrow_pending','escrow_funded',
                             'disbursement_pending','completed');
        RAISE NOTICE 'SAHA-037: exclusivity index CREATED — one executed deal per listing is now enforced at the database level.';
    ELSE
        RAISE WARNING 'SAHA-037: index still blocked by % listing(s): %', n, conflicts;
    END IF;
END $$;

COMMIT;
